#!/usr/bin/env python3
"""Compile runtime/shaders/*.vert|*.frag to SPIR-V and embed them in runtime/src/shaders_spv.h (committed, so a
build needs no shader compiler). Run after editing a shader.

Usage: python tools/gen_shaders.py [--check] [glslc]
The compiler defaults to the Android NDK's glslc or glslc on PATH.
"""
import argparse
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def find_glslc(explicit=None):
    if explicit:
        return explicit
    sdk = os.environ.get('ANDROID_HOME', os.path.expanduser('~/Library/Android/sdk'))
    for p in sorted(glob.glob(os.path.join(sdk, 'ndk', '*', 'shader-tools', '*', 'glslc*'))):
        return p
    return shutil.which('glslc') or sys.exit('glslc not found (Android NDK shader-tools or Vulkan SDK)')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='compile and compare without modifying the embedded header')
    parser.add_argument('glslc', nargs='?', help='path to the shader compiler')
    args = parser.parse_args()

    shader_dir = os.path.join(root, 'runtime', 'shaders')
    required = [os.path.join(shader_dir, name) for name in ('present.vert', 'present.frag')]
    missing = [os.path.basename(path) for path in required if not os.path.isfile(path)]
    if missing:
        sys.exit('Missing presentation shader sources: ' + ', '.join(missing) +
                 '. The existing header was not changed.')
    sources = sorted(glob.glob(os.path.join(shader_dir, '*.vert')) +
                     glob.glob(os.path.join(shader_dir, '*.frag')))
    glslc = find_glslc(args.glslc)
    out = ['// Generated by tools/gen_shaders.py from runtime/shaders. Do not edit.', '#pragma once', '#include <cstdint>', '']
    for src in sources:
        name = os.path.basename(src).replace('.', '_')
        with tempfile.TemporaryDirectory() as d:
            spv = os.path.join(d, 'out.spv')
            subprocess.run([glslc, '-O', '--target-env=vulkan1.0', src, '-o', spv], check=True)
            data = open(spv, 'rb').read()
        words = struct.unpack(f'<{len(data) // 4}I', data)
        out.append(f'inline constexpr uint32_t k_{name}[] = {{')
        for i in range(0, len(words), 8):
            out.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
        out.append('};')
        out.append('')
        print(f'{os.path.basename(src)}: {len(data)} bytes')
    header = os.path.join(root, 'runtime', 'src', 'shaders_spv.h')
    generated = '\n'.join(out)
    if args.check:
        try:
            with open(header, encoding='utf-8') as f:
                existing = f.read()
        except FileNotFoundError:
            sys.exit('Embedded shader header is missing.')
        if existing != generated:
            sys.exit('Embedded shader header differs from generated output; check the compiler version and shader sources.')
        print('Embedded shader header matches the generated output.')
    else:
        with open(header, 'w', encoding='utf-8') as f:
            f.write(generated)


if __name__ == '__main__':
    main()
